import { writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { MODEL_CODES } from '../website/station-3d/models/model-codes.js';
import { MODEL_CATALOG } from '../website/station-3d/viewers/model-catalog.js';
import { studyCatalog } from '../website/station-3d/viewers/model-studies.js';
import { generateModelCode, validateModelCodes } from '../website/station-3d/viewers/model-names.js';

const manifest = JSON.parse(readFileSync(new URL('../website/station-3d/models/viewer-studies.json', import.meta.url)));
const entries = [...MODEL_CATALOG, ...studyCatalog(manifest, null, 'http://localhost/')];
const codes = { ...MODEL_CODES };
const missing = entries.filter(entry => !codes[entry.id]);
if (process.argv.includes('--write')) {
    const used = new Set(Object.values(codes));
    for (const entry of missing) {
        codes[entry.id] = generateModelCode(used);
        used.add(codes[entry.id]);
    }
    validateModelCodes(entries, codes);
    const ordered = Object.fromEntries(Object.entries(codes).sort(([a], [b]) => a.localeCompare(b)));
    await writeFile(new URL('../website/station-3d/models/model-codes.js', import.meta.url), '// Generated by npm run models:codes. Codes are permanent; retain retired entries.\nexport const MODEL_CODES = Object.freeze(' + JSON.stringify(ordered, null, 4) + ');\n');
    console.log(`Assigned ${missing.length} new model codes; preserved ${Object.keys(MODEL_CODES).length} existing codes.`);
} else {
    validateModelCodes(entries, codes);
    console.log(`${entries.length} catalog models have unique permanent codes.`);
}
