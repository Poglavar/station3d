let cachedLang = null;

// The campaign script editor uses the same wording as the runtime, including
// notices reached through messageKey and the shared menu/failure controls.
export function campaignInterfaceText() {
    return Object.keys(dict.en).filter(key => key.startsWith('campaign.')).map(key => ({
        key, en: dict.en[key], hr: dict.hr[key] || '',
    }));
}

export function parseLanguageOverride(search) {
    try {
        const value = new URLSearchParams(String(search || '')).get('lang');
        const normalized = String(value || '').trim().toLowerCase();
        return SUPPORTED.includes(normalized) ? normalized : null;
    } catch (_) {
        return null;
    }
}

function detectLang() {
    // A shared QA/campaign link must be deterministic without overwriting the
    // visitor's persistent toggle preference for their next ordinary visit.
    const linked = typeof window !== 'undefined'
        ? parseLanguageOverride(window.location?.search)
        : null;
    if (linked) return linked;
    try {
        const saved = localStorage.getItem(STORAGE_KEY);
        if (SUPPORTED.includes(saved)) return saved;
    } catch (_) { /* localStorage may be unavailable in private mode */ }
    // Croatian, always, until the visitor says otherwise. This is a Croatian
    // site about Croatian cities and the campaign's Croatian is the written
    // original, so the browser's own language does not get a vote: an
    // English-locale Chrome in Zagreb is the common case, and it used to hide
    // the better half of the writing. The ?lang= link and the header toggle
    // above both still win, and the toggle's choice persists.
    return 'hr';
}

export function getLang() {
    if (cachedLang) return cachedLang;
    cachedLang = detectLang();
    try { document.documentElement.lang = cachedLang; } catch (_) {}
    return cachedLang;
}

export function setLang(code) {
    if (!SUPPORTED.includes(code)) return;
    if (cachedLang === code) return;
    cachedLang = code;
    try { localStorage.setItem(STORAGE_KEY, code); } catch (_) {}
    try { document.documentElement.lang = code; } catch (_) {}
    window.dispatchEvent(new CustomEvent('voznja:lang-changed', { detail: code }));
}

export function toggleLang() {
    setLang(getLang() === 'hr' ? 'en' : 'hr');
}

// Lookup with {key} interpolation. Falls back to English, then to the
// raw key — never throws, never returns undefined.
export function t(key, params) {
    const lang = getLang();
    const entry = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
    if (!params) return entry;
    return entry.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : ''));
}

// Subscribe to language changes. Returns an unsubscribe function. Use this
// from modules that hold mounted DOM whose text needs to refresh in place.
export function onLangChange(handler) {
    const wrapper = (e) => {
        // A lightweight host and the lazy production bundle can each import
        // this module. Both must read the language selected by either UI.
        if (!SUPPORTED.includes(e.detail)) return;
        cachedLang = e.detail;
        handler(e.detail);
    };
    window.addEventListener('voznja:lang-changed', wrapper);
    return () => window.removeEventListener('voznja:lang-changed', wrapper);
}
